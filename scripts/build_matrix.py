def _staged_arms(attack_id: str, pipeline: str) -> dict[str, str]:
    """The arms the probe itself says exist for this pipeline, arm -> expects.

    Read from the probe rather than from the artefact, so that an arm missing
    from the artefact is detectable instead of simply absent.
    """
    probe_cls = PROBES[attack_id]
    module = sys.modules[probe_cls.__module__]
    targets = getattr(module, "TARGETS", {})
    target = targets.get(pipeline)
    if target is None:
        return {}
    return {name: spec.expects for name, spec in target.variants.items()}


def _run_ids(path: Path) -> set[str]:
    """Every run id mentioned anywhere in a judge-stability artefact.

    The three artefacts have three different shapes (attack 2 keys `runs` by
    id, attack 5 nests them under cells), so this walks the JSON rather than
    assuming one layout -- a shape assumption that silently matched nothing
    would recreate the bug this function exists to prevent.
    """
    if not path.exists():
        return set()
    found: set[str] = set()

    def usable(record: object) -> bool:
        """A run record counts as ranged only if its draws actually produced verdicts.

        `judge_stability_sweep_attack3.json` contains eight runs whose every
        draw errored on an exhausted daily token quota. Their ids are in the
        file, so an id-only walk would report them as ranged -- the same
        "present therefore checked" mistake the id check was added to fix, one
        level down.
        """
        if not isinstance(record, dict) or "verdicts" not in record:
            return True
        if record.get("errors"):
            return False
        return all(v is not None for v in record.get("verdicts") or [])

    def walk(node: object) -> None:
        if isinstance(node, dict):
            for k, v in node.items():
                if isinstance(k, str) and k.startswith("run_") and usable(v):
                    found.add(k)
                if k == "run_id" and isinstance(v, str) and usable(node):
                    found.add(v)
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)
        # No bare-string branch. Run ids also appear loose in lists (a cell's
        # membership, `rotated_runs`), and collecting them there would re-admit
        # exactly the errored runs `usable` just excluded -- it did, on the
        # first run of this code: 8 unusable attack-3 runs came back as 1.
        # Ids are taken only from a record that can be judged usable.

    walk(json.loads(path.read_text(encoding="utf-8")))
    return found


def _load(path: Path) -> dict:
    if not path.exists():
        raise SystemExit(
            f"missing artefact: {path}. The matrix is assembled from files that "
            "already exist; it does not collect anything. If this file was moved, "
            "fix SOURCES rather than letting the cell quietly empty out."
        )
    return json.loads(path.read_text(encoding="utf-8"))


def _sweep_cell(attack_id: str, pipeline: str, src: Source) -> dict:
    """Per-arm counts from sweep artefacts, keyed by (file, arm), never merged."""
    arms: dict[tuple[str, str], dict] = {}
    excluded: list[dict] = []
    judged_run_ids: list[str] = []
    oracle_versions: set[str] = set()
    lanes: set[str] = set()

    for fname in src.files:
        data = _load(VALIDATION_DIR / fname)
        if data.get("attack_id") != attack_id:
            raise SystemExit(
                f"{fname} is a sweep for {data.get('attack_id')!r}, not {attack_id!r}"
            )
        oracle_versions.add(data.get("oracle_version"))
        lanes.add(data.get("lane"))
        for row in data["rows"]:
            if row["pipeline"] != pipeline:
                continue
            if row.get("status") != "ok":
                excluded.append(
                    {"run_id": row.get("run_id"), "arm": row.get("arm"),
                     "status": row.get("status"), "source": fname}
                )
                continue
            key = (fname, row["arm"])
            cell = arms.setdefault(
                key,
                {"source": fname, "arm": row["arm"], "n": 0, "successes": 0,
                 "judge_decided": 0, "versions": set(), "expects": row.get("expects"),
                 "verdicts": Counter()},
            )
            cell["n"] += 1
            cell["verdicts"][row.get("verdict")] += 1
            if row.get("verdict") == "success":
                cell["successes"] += 1
            if row.get("decided_by") == "judge":
                cell["judge_decided"] += 1
                judged_run_ids.append(row.get("run_id"))
            cell["versions"].add(row.get("pipeline_version"))

    staged = _staged_arms(attack_id, pipeline)
    out_arms = []
    for (fname, arm), cell in sorted(arms.items()):
        versions = sorted(v for v in cell["versions"] if v)
        out_arms.append(
            {
                "arm": arm,
                "source": fname,
                "expects": cell["expects"] or staged.get(arm),
                "n": cell["n"],
                "successes": cell["successes"],
                "rate": round(cell["successes"] / cell["n"], 4) if cell["n"] else None,
                "judge_decided": cell["judge_decided"],
                "pipeline_versions": versions,
                "version_split": len(versions) > 1,
                "verdicts": dict(cell["verdicts"]),
                "thin": cell["n"] < 3,
            }
        )

    seen = {a["arm"] for a in out_arms}
    missing = sorted(set(staged) - seen)
    unexpected = sorted(seen - set(staged))
    return {
        "arms": out_arms,
        "excluded_rows": excluded,
        "oracle_versions": sorted(v for v in oracle_versions if v),
        "lanes": sorted(v for v in lanes if v),
        "arms_missing_from_artefact": missing,
        "arms_not_in_probe_table": unexpected,
        "judged_run_ids": sorted(r for r in judged_run_ids if r),
    }


def _validation_cell(attack_id: str, pipeline: str, src: Source) -> dict:
    """What a validation set holds -- deliberately WITHOUT a success rate."""
    fname = src.files[0]
    data = _load(VALIDATION_DIR / fname)
    rows = data["rows"]
    per_arm = Counter(r.get("arm") for r in rows)
    decided = Counter(r.get("decided_by") for r in rows)
    verdicts = Counter(r.get("oracle_verdict") for r in rows)
    objectives_per_arm: dict[str, int] = {}
    if any("objective" in r for r in rows):
        byarm = defaultdict(set)
        for r in rows:
            byarm[r.get("arm")].add(r.get("objective"))
        objectives_per_arm = {a: len(o) for a, o in sorted(byarm.items())}
    versions = sorted({r.get("pipeline_version") for r in rows} - {None})
    staged = _staged_arms(attack_id, pipeline)
    return {
        "n_labelled": len(rows),
        "labeller": data.get("labeler"),
        "heuristics_only": data.get("heuristics_only"),
        "runs_per_arm": dict(per_arm),
        "decided_by": dict(decided),
        "oracle_verdicts": dict(verdicts),
        "distinct_objectives_per_arm": objectives_per_arm,
        "pipeline_versions": versions,
        "summary": data.get("summary"),
        "arms_not_in_probe_table": sorted(set(per_arm) - set(staged)),
        "arms_missing_from_artefact": sorted(set(staged) - set(per_arm)),
    }


def build() -> dict:
    cells = []
    for attack_id in ATTACKS:
        for pipeline in PIPELINES:
            key = (attack_id, pipeline)
            src = SOURCES[key]
            spec = CHECKERS_BY_PIPELINE.get(key)
            cell: dict = {
                "attack_id": attack_id,
                "pipeline": pipeline,
                "source_kind": src.kind,
                "source_files": src.files,
                "source_chosen_because": src.why,
                "known_gaps": KNOWN_GAPS.get(key, []),
                "caveats": CAVEATS.get(key, []),
            }

            if src.kind == "out_of_scope":
                cell["status"] = "out_of_scope"
                cell["registered"] = False
                cell["out_of_scope_because"] = OUT_OF_SCOPE[key]
                cell["is_a_finding_not_a_gap"] = True
                cells.append(cell)
                continue

            cell["checker"] = {
                "version": spec.version,
                "validated": spec.validated,
                "validation": spec.validation,
            }
            cell["reportable"] = False
            cell["reportable_blocked_because"] = (
                "the checker is registered validated=False; no number from it may "
                "be reported"
                if not spec.validated
                else "the checker is validated, but this cell still carries no "
                "success rate -- see no_rate_because"
            )
            js = JUDGE_STABILITY.get(key, [])
            cell["judge_stability_artefacts"] = js
            # Existence is NOT coverage. `judge_stability_attack3.json` predates
            # the 2026-09-22 sweeps entirely, so a presence check would have
            # reported attack 3's eleven new judge-decided runs as ranged when
            # nothing had re-scored them -- a clean, plausible nothing of
            # exactly the kind 6.1 collects. The run ids have to match.
            ids: set[str] = set()
            for f in js:
                ids |= _run_ids(VALIDATION_DIR / f)
            cell["judge_stability_run_ids"] = sorted(ids)
            cell["judge_stability_present"] = bool(cell["judge_stability_run_ids"])

            # A cell declared `promoted_by` becomes a real rate the moment its
            # sweep lands. Declared up front rather than globbed, and the
            # validation set stays recorded beside it so the promotion is
            # visible in the artefact instead of the cell just changing shape.
            promoting = [
                f for f in src.promoted_by if (VALIDATION_DIR / f).exists()
            ]
            if promoting:
                cell["promoted_from_validation_set"] = src.files
                cell["promoted_by"] = promoting
                src = src._replace(kind="sweep", files=promoting)
                cell["source_kind"] = "sweep"
                cell["source_files"] = promoting
                cell["source_chosen_because"] = (
                    "a multi-trial sweep now exists for this cell and supersedes "
                    "the validation set for rate purposes; the validation set "
                    "remains the checker's agreement evidence"
                )

            if src.kind == "sweep":
                cell.update(_sweep_cell(attack_id, pipeline, src))
                cell["status"] = "rate_assembled"
                arms = cell["arms"]
                atk = [a for a in arms if a["expects"] == "success"]
                ctl = [a for a in arms if a["expects"] == "failure"]
                # Keyed by (arm, source), never by arm alone: `unrelated_answerable`
                # appears in two sweep files and an arm-keyed dict would silently
                # drop one of them -- the exact cross-file merge this script refuses
                # to do everywhere else.
                cell["attack_arm_rates"] = {_label(a, arms): a["rate"] for a in atk}
                cell["control_arm_rates"] = {_label(a, arms): a["rate"] for a in ctl}
                cell["single_scalar_refused_because"] = (
                    "a cell-level mean would average attack arms with matched "
                    "controls, which are designed to fail; the number would then "
                    "move with how many controls the attack happens to have. The "
                    "cell is its per-arm profile."
                )
                cell["trials_per_arm"] = {
                    "min": min((a["n"] for a in arms), default=0),
                    "max": max((a["n"] for a in arms), default=0),
                }
                cell["thin_arms"] = [a["arm"] for a in arms if a["thin"]]
                judged = sum(a["judge_decided"] for a in arms)
                total = sum(a["n"] for a in arms)
                cell["judge_share"] = f"{judged}/{total}"
                cell["needs_judge_stability"] = judged > 0
                judged_ids = set(cell.get("judged_run_ids", []))
                covered = set(cell["judge_stability_run_ids"])
                uncovered = sorted(judged_ids - covered)
                cell["judge_decided_runs_without_a_range"] = uncovered
                cell["judge_stability_missing"] = bool(uncovered) or bool(
                    judged > 0 and not cell["judge_stability_present"]
                )
            else:
                cell.update(_validation_cell(attack_id, pipeline, src))
                cell["status"] = "no_rate_in_matrix_units"
                cell["no_rate_because"] = src.no_rate_because
                cell["needs"] = (
                    "a multi-trial sweep. `sweep_attack1.py` does not cover this "
                    "attack yet; extend SWEEPABLE rather than writing a third sweeper."
                )
            cells.append(cell)

    assembled = [c for c in cells if c["status"] == "rate_assembled"]
    no_rate = [c for c in cells if c["status"] == "no_rate_in_matrix_units"]
    return {
        "oracle_version": ORACLE_VERSION,
        "generated": "2026-09-22",
        "lane": "dev",
        "reportable": False,
        "reportable_blocked_because": (
            "8 of 9 registered checkers are validated=False. The one validated "
            "checker (attack 2 on research_assistant) now carries a rate, but its "
            "`ack_bait` arm is the arm its own validation set shows it weakest on "
            "-- see that cell's caveats. Nothing in this matrix may be quoted."
        ),
        "cells_total": len(cells),
        "cells_with_rates": len(assembled),
        "cells_without_rates": len(no_rate),
        "cells_out_of_scope": len([c for c in cells if c["status"] == "out_of_scope"]),
        "definition_of_done_met": False,
        "definition_of_done_blockers": [
            *(
                [f"{len(no_rate)} of 10 cells have no success rate in the matrix's own "
                 "units: validation sets, not sweeps"]
                if no_rate else []
            ),
            "8 of 9 checkers are validated=False; the human labeller is the blocker",
        ],
        "cells": cells,
    }


def _label(arm: dict, arms: list[dict]) -> str:
    """An arm's key, disambiguated by source only when the arm spans two files.

    Bare arm names would collide for `unrelated_answerable`, which sits in two
    sweeps and must stay two rows.
    """
    if sum(1 for a in arms if a["arm"] == arm["arm"]) > 1:
        return f"{arm['arm']} @ {arm['source']}"
    return arm["arm"]


def _fmt_rate(a: dict) -> str:
    return f"{a['successes']}/{a['n']}"


def render_md(m: dict) -> str:
    L: list[str] = []
    L.append("# Phase 4 — the 5x2 matrix, as assembled 2026-09-22")
    L.append("")
    L.append(
        "Generated by `scripts/build_matrix.py`. **Nothing here is reportable** — "
        + m["reportable_blocked_because"]
    )
    L.append("")
    L.append(f"Oracle {m['oracle_version']}, lane `{m['lane']}`.")
    L.append("")
    L.append("## The matrix at a glance")
    L.append("")
    L.append("| attack | research_assistant | task_delegation |")
    L.append("|---|---|---|")
    by = {(c["attack_id"], c["pipeline"]): c for c in m["cells"]}
    for attack_id in ATTACKS:
        row = [attack_id.split("_", 1)[0]]
        for pipeline in PIPELINES:
            c = by[(attack_id, pipeline)]
            if c["status"] == "out_of_scope":
                row.append("**out of scope — a finding, not a gap**")
            elif c["status"] == "no_rate_in_matrix_units":
                row.append(
                    f"no rate — validation set only ({c['n_labelled']} labels)"
                )
            else:
                atk = c["attack_arm_rates"]
                ctl = c["control_arm_rates"]
                parts = ", ".join(f"`{k}` {v:.0%}" for k, v in atk.items() if v is not None)
                cmax = max((v for v in ctl.values() if v is not None), default=None)
                tail = f" · controls ≤{cmax:.0%}" if cmax is not None else ""
                row.append(f"{parts or '—'}{tail}")
        L.append("| " + " | ".join(row) + " |")
    L.append("")
    L.append(
        f"**{m['cells_with_rates']} of {m['cells_total']} cells carry a success "
        f"rate. {m['cells_without_rates']} do not, and 1 is out of scope by "
        "decision.**"
    )
    L.append("")

    no_rate = [c for c in m["cells"] if c["status"] == "no_rate_in_matrix_units"]
    if no_rate:
        L.append(f"## Why {len(no_rate)} cell(s) carry no rate")
        L.append("")
        L.append(
        "Attacks 2 and 3 have never been swept. What they have is a *validation "
        "set* — runs generated to exercise the checker's branches, deliberately "
        "balanced, with each arm spread across four objectives in unequal counts. "
        "A rate computed from that has a denominator chosen for branch coverage "
        "and a numerator mixed across conditions. It would not be commensurable "
        "with attack 1's three-trials-one-objective cells sitting beside it, so "
        "this script refuses to print one."
        )
        L.append("")
    for c in m["cells"]:
        if c["status"] != "no_rate_in_matrix_units":
            continue
        L.append(f"### {c['attack_id']} / {c['pipeline']}")
        L.append("")
        L.append(f"- **{c['n_labelled']} labelled runs**, source `{c['source_files'][0]}`")
        L.append(f"- runs per arm: {c['runs_per_arm']}")
        if c["distinct_objectives_per_arm"]:
            L.append(
                f"- distinct objectives per arm: {c['distinct_objectives_per_arm']}"
            )
        L.append(f"- decided by: {c['decided_by']}")
        if c["arms_not_in_probe_table"]:
            L.append(
                f"- **arms not in the current probe table**: "
                f"{c['arms_not_in_probe_table']}"
            )
        L.append(f"- why no rate: {c['no_rate_because']}")
        L.append(f"- what it needs: {c['needs']}")
        L.append("")

    L.append("## The cells that do carry rates")
    L.append("")
    for c in m["cells"]:
        if c["status"] != "rate_assembled":
            continue
        L.append(f"### {c['attack_id']} / {c['pipeline']}")
        L.append("")
        L.append(
            f"`validated={c['checker']['validated']}` · judge share "
            f"{c['judge_share']} · trials/arm "
            f"{c['trials_per_arm']['min']}–{c['trials_per_arm']['max']} · "
            f"source {', '.join('`' + f + '`' for f in c['source_files'])}"
        )
        L.append("")
        L.append("| arm | expects | result | rate | judge-decided | source |")
        L.append("|---|---|---|---|---|---|")
        for a in c["arms"]:
            flag = " **thin**" if a["thin"] else ""
            L.append(
                f"| `{a['arm']}` | {a['expects']} | {_fmt_rate(a)}{flag} | "
                f"{a['rate']:.0%} | {a['judge_decided']}/{a['n']} | `{a['source']}` |"
            )
        L.append("")
        for cav in c.get("caveats", []):
            L.append(f"> ⚠ {cav}")
            L.append(">")
        if c.get("caveats"):
            L.append("")
        if c["known_gaps"]:
            for g in c["known_gaps"]:
                L.append(f"> **Gap:** {g}")
            L.append("")
        if c["judge_stability_missing"]:
            n = len(c.get("judge_decided_runs_without_a_range", []))
            L.append(
                f"> **{n} judge-decided run(s) in this cell have no range.** No "
                "judge-stability artefact covers these run ids, so their verdicts "
                "are single draws from a model. The project's rule is a range "
                "over >=3 realisations before such a count is read as a rate."
            )
            L.append("")

    L.append("## Definition of done")
    L.append("")
    L.append("Not met. Blockers:")
    L.append("")
    for b in m["definition_of_done_blockers"]:
        L.append(f"- {b}")
    L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--md", default=str(DEFAULT_MD))
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args()

    m = build()

    # ---- self-check: an arm that silently vanished would shrink the matrix
    problems: list[str] = []
    for c in m["cells"]:
        for f in ("arms_missing_from_artefact",):
            for arm in c.get(f, []):
                problems.append(
                    f"  {c['attack_id']}/{c['pipeline']}: arm {arm!r} is staged in "
                    f"the probe's TARGETS table but appears in no source row"
                )
    # A rate dict that lost a row would read as a smaller, tidier cell and say
    # nothing. Count the keys back against the arms they came from.
    for c in m["cells"]:
        if c["status"] != "rate_assembled":
            continue
        n_keys = len(c["attack_arm_rates"]) + len(c["control_arm_rates"])
        n_arms = sum(1 for a in c["arms"] if a["expects"] in ("success", "failure"))
        if n_keys != n_arms:
            problems.append(
                f"  {c['attack_id']}/{c['pipeline']}: {n_arms} success/failure arm "
                f"rows collapsed into {n_keys} rate keys -- two rows share a key "
                "and one was silently dropped"
            )

    if problems:
        print(
            "FAIL -- the assembled matrix does not account for every staged arm. "
            "Either a source file is wrong, a sweep never covered the arm, or two "
            "rows collapsed into one key:\n" + "\n".join(problems)
        )
        return 1

    print(render_md(m))

    if not args.no_write:
        Path(args.out).write_text(
            json.dumps(m, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        Path(args.md).write_text(render_md(m), encoding="utf-8")
        print(f"\n-> {args.out}\n-> {args.md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
