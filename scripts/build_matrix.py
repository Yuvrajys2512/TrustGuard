#!/usr/bin/env python
"""Assemble Phase 4's 5x2 matrix from the artefacts that exist, and mark what is missing.

    python scripts/build_matrix.py              # print the matrix, write the JSON
    python scripts/build_matrix.py --no-write   # print only

This is the Phase 4 "definition of done" object: five attacks x two pipelines,
each cell an oracle-scored success rate with variance across trials. It
**collects nothing and scores nothing.** It reads sweep artefacts that already
exist, groups them, and states per cell what is there and what is not.

## The thing this script exists to get right

The ten cells are **not backed by the same kind of artefact**, and the
difference is not cosmetic.

- Attacks **1, 4 and 5** have *sweeps*: a ladder of arms, a fixed objective, N
  trials per arm, one config. A per-arm count over those runs is a success rate
  with a denominator that means something.
- Attacks **2 and 3** have *validation sets*: runs generated by
  `build_validation_set*.py` to exercise the checker's branches. That corpus was
  deliberately **balanced** -- its own docstring says it exists because Phase 2
  "left a corpus with no failures in it" -- and it spreads each arm across
  **four different objectives** in unequal counts (attack 3's `hedged` arm is
  2/2/5/1 across four objectives). Those are not repeated trials of one cell.

So a success rate computed from a validation set would have a denominator
chosen for branch coverage and a numerator mixed across conditions, and it
would sit in the same table as attack 1's 3-trials-one-objective cells as
though the two were commensurable. **They are not, and this script refuses to
emit a rate for those cells** rather than printing a number that would be read
as one. The refusal is recorded per cell as `status` and `no_rate_because`.

This is the same failure §6.2 of the handoff names four times at the *arm*
level -- an arm that cannot come out the way the definition needs -- hoisted to
the matrix level: a cell whose number cannot mean what the column heading says.

## What attacks 2 and 3 DO have, and why it is not this

Attack 2 on pipeline #1 is the project's one `validated=True` checker, and its
headline figures (91.3% agreement, kappa 0.827, 95.7% on the deterministic
half) are **oracle-versus-human agreement**: a property of the *checker*, not
of the attack. An agreement number is not a success rate and must never be
carried into a success-rate cell. The script records it in its own field,
`checker.validation`, and leaves the rate null.

## Aggregation rules it enforces rather than assumes

- **Cells are keyed by (source file, pipeline, arm).** Never merged across
  files. `unrelated_answerable` appears in both `sweep_attack1.json` (3 runs)
  and `sweep_attack1_ua.json` (6 runs) and they are reported as two rows, per
  the no-aggregation-across-arm-edits rule.
- **Never across a `pipeline_version` bump.** Rows are grouped by the version
  recorded on them and a cell carrying more than one version is flagged
  `version_split` rather than summed.
- **`status != "ok"` rows are excluded** from counts and reported separately.

## The self-check it runs, and why it has one

Four of this project's defects signalled with silence, and an assembly script
is a perfect place for a fifth: a source file that fails to load, or an arm
that quietly never appears, would produce a smaller, cleaner-looking matrix and
nothing would say so. So the script cross-checks every cell's arms against the
probe's **own** `TARGETS[pipeline].variants` table and fails loudly if a staged
arm is missing from the artefact without being declared. "No findings" is only
trustworthy from a tool that confirms it looked.
"""

